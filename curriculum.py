def render_sweet_spot_diagram() -> bytes:
    """
    '입술 시술시 최적의 깊이(Sweet Spot)'를 설명하는 자체 제작 단면 도식.
    원본 PPT의 실사 피부 단면 사진을 복제하지 않고, 피부 층을 색상 띠로
    단순화한 오리지널 다이어그램으로 같은 개념(깊이에 따른 결과 차이)을 전달합니다.
    """
    fig, ax = plt.subplots(figsize=(7, 4.2))

    layers = [
        ("표피층", 0.80, 1.00, "#f6d9c4"),
        ("기저막", 0.72, 0.80, "#e8b48c"),
        ("유두층 상부 (Sweet Spot)", 0.55, 0.72, "#f49aa6"),
        ("고유진피층", 0.25, 0.55, "#c76a7a"),
        ("점막하층", 0.00, 0.25, "#8a4a57"),
    ]
    for label, y0, y1, c in layers:
        ax.add_patch(mpatches.Rectangle((0.0, y0), 1.0, y1 - y0, facecolor=c, edgecolor="white"))
        ax.text(1.03, (y0 + y1) / 2, label, va="center", ha="left", fontsize=10,
                fontproperties=KOREAN_FONT)

    # Sweet spot 강조 테두리
    ax.add_patch(mpatches.Rectangle((0.0, 0.55), 1.0, 0.17, facecolor="none",
                                     edgecolor="#2d7dd2", linewidth=2.5))
    ax.annotate("권장 깊이: 0.2~0.7mm\n(기저막 바로 아래 ~ 유두층 상부)",
                xy=(0.5, 0.635), xytext=(0.5, 1.28),
                ha="center", fontsize=9, color="#2d7dd2",
                arrowprops=dict(arrowstyle="->", color="#2d7dd2"),
                fontproperties=KOREAN_FONT)

    ax.annotate("너무 얕음 →\n얹힌 듯 텁텁, 얼룩/잔흔",
                xy=(1.18, 0.9), fontsize=8.5, color="#b3541e", fontproperties=KOREAN_FONT)
    ax.annotate("너무 깊음 →\n멍·출혈·탁한 변색",
                xy=(1.18, 0.1), fontsize=8.5, color="#8a1f2b", fontproperties=KOREAN_FONT)

    ax.set_xlim(-0.05, 2.0)
    ax.set_ylim(0, 1.4)
    ax.axis("off")
    ax.set_title("입술 시술 깊이 — Sweet Spot 개념도 (자체 제작, 원본 사진 아님)", fontsize=11,
                 fontproperties=KOREAN_FONT)

    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150, bbox_inches="tight")
    plt.close(fig)
    return buf.getvalue()


def render_gradation_diagram() -> bytes:
    """
    '그라데이션 쉽게 표현하기'를 설명하는 자체 제작 개념도.
    원본의 손그림 입술 일러스트를 복제하지 않고, 추상적인 동심 타원 구역으로
    같은 교육 포인트(중앙 진하게 → 외곽 연하게)를 전달합니다.
    """
    fig, ax = plt.subplots(figsize=(6, 4))

    outer = mpatches.Ellipse((0.5, 0.5), 0.9, 0.55, facecolor="#f6b8c2", edgecolor="#333333")
    inner = mpatches.Ellipse((0.5, 0.5), 0.45, 0.28, facecolor="#e8536c", edgecolor="#333333")
    ax.add_patch(outer)
    ax.add_patch(inner)

    ax.annotate("1번 구간\n(중앙, 먼저·진하게)", xy=(0.5, 0.5), ha="center", va="center",
                fontsize=9.5, color="white", fontweight="bold", fontproperties=KOREAN_FONT)
    ax.annotate("외곽 구간\n(나중·더 연하게)", xy=(0.5, 0.85), ha="center", va="center",
                fontsize=9.5, color="#8a2d3b", fontproperties=KOREAN_FONT)

    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")
    ax.set_title("그라데이션 시술 개념도 (자체 제작, 원본 일러스트 아님)", fontsize=11,
                 fontproperties=KOREAN_FONT)

    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150, bbox_inches="tight")
    plt.close(fig)
    return buf.getvalue()


